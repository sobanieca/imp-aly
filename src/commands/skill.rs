#[derive(Debug, PartialEq, Eq)]
pub struct SkillRoot {
    pub dir: String,
    pub reason: &'static str,
    pub global: bool,
}

fn exists(path: &str) -> bool {
    fs::symlink_metadata(path).is_ok()
}

pub fn find_skill_root(start: &str, home: &str) -> SkillRoot {
    let mut dir = start.to_string();
    loop {
        if exists(&join(&[&dir, ".git"])) {
            return SkillRoot {
                dir,
                reason: "git root",
                global: false,
            };
        }
        let parent = dirname(&dir);
        if dir == home || parent == dir {
            break;
        }
        dir = parent;
    }
    SkillRoot {
        dir: home.to_string(),
        reason: "not in a git repository",
        global: true,
    }
}

/// Marks a skill file written by `imp-aly skill --init`. `imp-aly update`
/// rewrites only the files that still have it.
const MARKER: &str = "<!-- Generated by `imp-aly skill --init`";

/// The skill with the marker line right after the front matter, where the
/// agents still read the front matter.
pub fn generated_skill() -> String {
    let marker = format!(
        "{MARKER}. `imp-aly update` rewrites this file; delete this line to keep your own changes. -->\n"
    );
    match SKILL_CONTENT
        .strip_prefix("---\n")
        .and_then(|rest| rest.find("\n---\n"))
    {
        Some(end) => {
            let split = "---\n".len() + end + "\n---\n".len();
            format!(
                "{}{marker}{}",
                &SKILL_CONTENT[..split],
                &SKILL_CONTENT[split..]
            )
        }
        None => format!("{marker}{SKILL_CONTENT}"),
    }
}

fn is_generated(text: &str) -> bool {
    text.lines().any(|line| line.starts_with(MARKER))
}

/// The home folder of the user that ran `sudo imp-aly update`. The update
/// runs as root, but the skills belong to that user.
fn sudo_home() -> Option<String> {
    // SAFETY: geteuid has no preconditions.
    if unsafe { libc::geteuid() } != 0 {
        return None;
    }
    let uid: u32 = std::env::var("SUDO_UID").ok()?.parse().ok()?;
    // SAFETY: getpwuid returns null or a pointer to a static passwd entry,
    // read before any other call to getpwuid.
    unsafe {
        let entry = libc::getpwuid(uid);
        if entry.is_null() || (*entry).pw_dir.is_null() {
            return None;
        }
        Some(
            std::ffi::CStr::from_ptr((*entry).pw_dir)
                .to_string_lossy()
                .into_owned(),
        )
    }
}

/// The home folder of the user, also under sudo.
pub fn skill_home() -> String {
    sudo_home().unwrap_or_else(home)
}

fn skill_files(root: &str) -> Vec<String> {
    SKILL_TARGETS
        .iter()
        .map(|(dir, _)| join(&[root, dir, SKILL_NAME, "SKILL.md"]))
        .collect()
}

/// The git root around `start`, searched up to the home folder.
fn git_root(start: &str, home: &str) -> Option<String> {
    let root = find_skill_root(start, home);
    (!root.global).then_some(root.dir)
}

/// Writes the skill for each agent, replacing the files that exist. Returns
/// the paths, the agents and whether the file existed.
pub fn install_skill(root: &str) -> Result<Vec<(String, &'static str, bool)>> {
    let content = generated_skill();
    let mut written = Vec::new();
    for (dir, read_by) in SKILL_TARGETS {
        let path = join(&[dir, SKILL_NAME, "SKILL.md"]);
        let file = join(&[root, &path]);
        let existed = exists(&file);
        fs::create_dir_all(dirname(&file)).map_err(|error| Error::io(&error, &file))?;
        fs::write(&file, &content).map_err(|error| Error::io(&error, &file))?;
        written.push((path, read_by, existed));
    }
    Ok(written)
}

/// The skill files under `root` that still have the marker.
fn generated_files(root: &str) -> Vec<String> {
    skill_files(root)
        .into_iter()
        .filter(|file| fs::read_to_string(file).is_ok_and(|text| is_generated(&text)))
        .collect()
}

/// Rewrites the skills that `imp-aly skill --init` wrote, when they still
/// have the marker: the ones at the git root of `cwd`, else (no repository,
/// or no generated skill in it) the ones in the home folder. Returns the
/// lines to print: the files it changed. `imp-aly update` runs it with the new
/// binary (`imp-aly skill --refresh`), so the new skill text is written.
pub fn refresh(cwd: &str, home: &str) -> Vec<String> {
    let files = git_root(cwd, home)
        .map(|root| generated_files(&root))
        .filter(|files| !files.is_empty())
        .unwrap_or_else(|| generated_files(home));

    let content = generated_skill();
    let mut updated = Vec::new();
    let mut errors = Vec::new();
    for file in files {
        if fs::read_to_string(&file).is_ok_and(|text| text == content) {
            continue;
        }
        // Writing in place keeps the owner of the file, also under sudo.
        match fs::write(&file, &content) {
            Ok(()) => updated.push(format!("  {file}")),
            Err(error) => errors.push(format!("cannot update the skill {file}: {error}")),
        }
    }
    let mut lines = Vec::new();
    if !updated.is_empty() {
        lines.push("Updated skills:".to_string());
        lines.extend(updated);
    }
    lines.extend(errors);
    lines
}

pub fn skill(parsed: &Parsed) -> Result<()> {
    require_only_flags(parsed, &["init", "refresh"], "skill")?;
    if parsed.positional.len() > 1 {
        return Err(Error::new("use: imp-aly skill [--init]"));
    }
    // Not in the help: `imp-aly update` runs the new binary with it.
    if parsed.has("refresh") {
        for line in refresh(&cwd(), &skill_home()) {
            logger::plain(line);
        }
        return Ok(());
    }
    if !parsed.has("init") {
        println!("{AGENT_INSTRUCTIONS}");
        println!("{}", help_text());
        return Ok(());
    }
    let home = home();
    let root = find_skill_root(&cwd(), &home);
    let files = install_skill(&root.dir)?;
    if root.global {
        logger::plain(format!(
            "Not in a git repository - the skill is for all projects, in {}",
            root.dir
        ));
    } else {
        logger::plain(format!("Project root: {} ({})", root.dir, root.reason));
    }
    for (path, read_by, existed) in files {
        let action = if existed { "Updated" } else { "Created" };
        logger::plain(format!("{action} {path}  ({read_by})"));
    }
    logger::plain("");
    logger::plain("Try: /imp-aly how many visits did myapp have last week, per page");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testing::TempDir;

    #[test]
    fn in_a_git_repository_the_skill_goes_to_the_git_root() {
        let dir = TempDir::new();
        let home = dir.join("home");
        fs::create_dir_all(format!("{home}/repo/.git")).unwrap();
        fs::create_dir_all(format!("{home}/repo/packages/app/src")).unwrap();
        let root = find_skill_root(&format!("{home}/repo/packages/app/src"), &home);
        assert_eq!(
            root,
            SkillRoot {
                dir: format!("{home}/repo"),
                reason: "git root",
                global: false
            }
        );
    }

    #[test]
    fn outside_a_git_repository_the_skill_goes_to_the_home_folder() {
        let dir = TempDir::new();
        let home = dir.join("home");
        fs::create_dir_all(dir.join(".git")).unwrap();
        fs::create_dir_all(format!("{home}/notes")).unwrap();
        fs::create_dir_all(dir.join("other")).unwrap();
        let root = find_skill_root(&format!("{home}/notes"), &home);
        assert_eq!(
            root,
            SkillRoot {
                dir: home.clone(),
                reason: "not in a git repository",
                global: true
            }
        );
        assert_eq!(find_skill_root(&home, &home).dir, home);
        assert_eq!(find_skill_root(&dir.join("other"), &home).dir, dir.path);
    }

    #[test]
    fn the_skill_is_written_for_each_agent_and_replaced() {
        let dir = TempDir::new();
        let files = install_skill(&dir.path).unwrap();
        let paths: Vec<&str> = files.iter().map(|(path, _, _)| path.as_str()).collect();
        assert_eq!(
            paths,
            [
                ".agents/skills/imp-aly/SKILL.md",
                ".claude/skills/imp-aly/SKILL.md"
            ]
        );
        assert!(files.iter().all(|(_, _, existed)| !existed));
        for path in &paths {
            assert_eq!(
                fs::read_to_string(dir.join(path)).unwrap(),
                generated_skill()
            );
        }
        assert!(SKILL_CONTENT.starts_with("---\nname: imp-aly\n"));
        assert!(generated_skill().contains("\n---\n<!-- Generated by `imp-aly skill --init`. "));

        fs::write(dir.join(".claude/skills/imp-aly/SKILL.md"), "edited").unwrap();
        let files = install_skill(&dir.path).unwrap();
        assert!(files.iter().all(|(_, _, existed)| *existed));
        assert_eq!(
            fs::read_to_string(dir.join(".claude/skills/imp-aly/SKILL.md")).unwrap(),
            generated_skill()
        );
    }

    #[test]
    fn refresh_rewrites_the_generated_skills() {
        let dir = TempDir::new();
        let home = dir.join("home");
        let repo = join(&[&home, "repo"]);
        let empty = join(&[&home, "empty"]);
        let other = join(&[&home, "other"]);
        for root in [&repo, &empty, &other] {
            fs::create_dir_all(join(&[root, ".git"])).unwrap();
        }
        for root in [&repo, &other, &home] {
            install_skill(root).unwrap();
        }
        let marker = generated_skill()
            .lines()
            .find(|line| line.starts_with(MARKER))
            .unwrap()
            .to_string();
        let stale = format!("---\nname: imp-aly\n---\n{marker}\nold\n");
        let claude = |root: &str| join(&[root, ".claude/skills/imp-aly/SKILL.md"]);
        for root in [&repo, &other, &home] {
            fs::write(claude(root), &stale).unwrap();
        }
        let own = join(&[&repo, ".agents/skills/imp-aly/SKILL.md"]);
        fs::write(&own, "my own skill").unwrap();
        let read = |file: &str| fs::read_to_string(file).unwrap();
        let listed =
            |root: &str| vec!["Updated skills:".to_string(), format!("  {}", claude(root))];

        // In a repository with the skill: only that skill.
        assert_eq!(refresh(&join(&[&repo, "src"]), &home), listed(&repo));
        assert_eq!(read(&claude(&repo)), generated_skill());
        assert_eq!(read(&own), "my own skill");
        assert_eq!(read(&claude(&home)), stale);

        // In a repository without the skill: the skill in the home folder.
        assert_eq!(refresh(&empty, &home), listed(&home));
        assert_eq!(read(&claude(&other)), stale);
        assert!(refresh(&home, &home).is_empty());
    }
}
